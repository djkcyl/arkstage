#!/usr/bin/env node
// Build the standalone `resources` branch payload consumed by Arkstage at runtime.
//
// Usage:
//   node tools/build-resources/build-bookshelf-resources.mjs /tmp/arkstage-resources
//
// Source images are the maintainer-side extraction output. They are deliberately
// removed from the application bundle; this tool publishes content-addressed
// copies plus metadata.json for jsDelivr.

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { promises as fs, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..", "..");
const OUT = path.resolve(process.argv[2] || path.join(ROOT, "build", "resources"));
const STORYLINES = path.join(HERE, "storylines.json");
const SOURCE_DIR = path.join(ROOT, "build", "resources-source");
const COVER_DIMS = path.join(SOURCE_DIR, "cover-dims.json");

function hash(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

async function copyArt(kind, sourceDir, knownDims = {}) {
  const result = {};
  const outDir = path.join(OUT, kind);
  await fs.mkdir(outDir, { recursive: true });
  const files = (await fs.readdir(sourceDir)).filter((f) => f.endsWith(".webp")).sort();
  for (const file of files) {
    const key = file.slice(0, -".webp".length);
    const source = path.join(sourceDir, file);
    const bytes = readFileSync(source);
    const digest = hash(bytes);
    const destName = `${digest.slice(0, 20)}.webp`;
    const dims = knownDims[key] || execFileSync("identify", ["-format", "%w %h", source])
      .toString()
      .trim()
      .split(" ")
      .map(Number);
    await fs.writeFile(path.join(outDir, destName), bytes);
    result[key] = { path: `${kind}/${destName}`, width: dims[0], height: dims[1] };
  }
  return result;
}

async function main() {
  await fs.rm(OUT, { recursive: true, force: true });
  await fs.mkdir(OUT, { recursive: true });
  const storylines = JSON.parse(readFileSync(STORYLINES, "utf8"));
  const coverDims = JSON.parse(readFileSync(COVER_DIMS, "utf8"));
  const covers = await copyArt("covers", path.join(SOURCE_DIR, "covers"), coverDims);
  const banners = await copyArt("banners", path.join(SOURCE_DIR, "banners"));

  const payload = {
    schemaVersion: 1,
    version: "",
    storylines,
    covers,
    banners,
    fallbackCategory: "特殊&未分类",
    scenarioLinks: {},
  };
  payload.version = hash(JSON.stringify(payload)).slice(0, 20);
  await fs.writeFile(path.join(OUT, "metadata.json"), `${JSON.stringify(payload, null, 2)}\n`);
  await fs.writeFile(
    path.join(OUT, "README.md"),
    "# Arkstage runtime resources\n\nGenerated by `tools/build-resources/build-bookshelf-resources.mjs`.\n"
  );
  console.log(`Wrote ${Object.keys(covers).length} covers, ${Object.keys(banners).length} banners; version ${payload.version}`);
}

main().catch((error) => {
  console.error(error?.stack || error);
  process.exit(1);
});
